import { BaseExporter } from './BaseExporter.js';

export class MarkdownExporter extends BaseExporter {
  constructor() {
    super('markdown');
  }

  async export(documentData) {
    const lines = [];

    // 1. Cover Page
    lines.push(`# ${documentData.projectName || 'Repository Technical Specification'}`);
    lines.push('');
    lines.push(`**Prepared For**: Systems Architecture & Integration`);
    lines.push(`**Repository URL**: [${documentData.repoUrl}](${documentData.repoUrl})`);
    lines.push(`**Owner**: ${documentData.repoOwner || 'Unknown'}`);
    lines.push(`**Branch**: \`${documentData.repoBranch || 'main'}\``);
    lines.push(`**Commit**: \`${documentData.commitHash || 'HEAD'}\``);
    lines.push(`**Documentation Version**: ${documentData.documentationVersion || '1.0'}`);
    lines.push(`**Generated Date**: ${documentData.generatedDate || new Date().toLocaleString()}`);
    lines.push(`**Technology Stack**: ${documentData.techStackText || 'Polyglot'}`);
    lines.push('');
    lines.push(`*Generated by Adaptive Semantic Documentation Synchronization Engine (ASDSE)*`);
    lines.push('');
    lines.push('---');
    lines.push('');

    // 2. Table of Contents
    lines.push('## Table of Contents');
    lines.push('');
    documentData.sections.forEach((sec, idx) => {
      lines.push(`${idx + 1}. [${sec.title}](#${sec.title.toLowerCase().replace(/[^a-z0-9]+/g, '-')})`);
    });
    lines.push('');
    lines.push('---');
    lines.push('');

    // 3. Sections Content
    documentData.sections.forEach((sec, idx) => {
      lines.push(`## ${idx + 1}. ${sec.title}`);
      lines.push('');
      if (sec.content) {
        lines.push(sec.content);
        lines.push('');
      } else {
        lines.push('*Information not found in repository.*');
        lines.push('');
      }
      lines.push('---');
      lines.push('');
    });

    const fullMarkdown = lines.join('\n');
    return Buffer.from(fullMarkdown, 'utf-8');
  }
}
