export class DocumentExporter {
  /**
   * Bundles all 17 documents into a single consolidated Markdown package.
   */
  static exportMarkdown(documents = [], projectName = 'Repository') {
    let md = `# Comprehensive Technical Documentation: ${projectName}\n\n`;
    md += `*Generated by RepoMind AI & ASDSE Platform*\n`;
    md += `*Timestamp: ${new Date().toISOString()}*\n\n---\n\n`;

    for (const doc of documents) {
      md += `${doc.content}\n\n---\n\n`;
    }

    return md;
  }

  /**
   * Generates a clean standalone HTML presentation bundle.
   */
  static exportHTML(documents = [], projectName = 'Repository') {
    const bodyContent = documents.map(d => `
      <section id="${d.documentId}" style="margin-bottom: 40px; border-bottom: 1px solid #334155; padding-bottom: 20px;">
        <h2>${d.title}</h2>
        <div style="white-space: pre-wrap; font-family: -apple-system, BlinkMacSystemFont, sans-serif; line-height: 1.6;">
          ${d.content.replace(/</g, '&lt;').replace(/>/g, '&gt;')}
        </div>
      </section>
    `).join('\n');

    return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <title>${projectName} — Technical Documentation</title>
  <style>
    body { background-color: #0F172A; color: #F8FAFC; font-family: system-ui, sans-serif; padding: 40px; max-width: 1000px; margin: auto; }
    h1 { color: #38BDF8; border-bottom: 2px solid #0284C7; padding-bottom: 10px; }
    h2 { color: #818CF8; margin-top: 30px; }
    h3 { color: #34D399; }
    code { background: #1E293B; padding: 2px 6px; border-radius: 4px; color: #F472B6; font-family: monospace; }
  </style>
</head>
<body>
  <h1>${projectName} — Enterprise Technical Documentation</h1>
  <p>Generated by <strong>RepoMind AI</strong> | Verified Evidence-Backed Documentation</p>
  <hr style="border-color: #1E293B; margin: 20px 0;"/>
  ${bodyContent}
</body>
</html>`;
  }

  /**
   * Exports full JSON documentation package.
   */
  static exportJSON(documents = [], metadata = {}) {
    return JSON.stringify({
      projectName: metadata.projectName || 'Repository',
      generatedAt: new Date().toISOString(),
      documentsCount: documents.length,
      documents
    }, null, 2);
  }
}
